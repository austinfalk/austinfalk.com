// @ts-check
import { defineConfig, fontProviders } from 'astro/config';
import react from '@astrojs/react';
import sitemap from '@astrojs/sitemap';
import { readFileSync } from 'node:fs';
import tailwindcss from '@tailwindcss/vite';
import { satteri } from '@astrojs/markdown-satteri';
import { headingAnchors } from './src/lib/heading-anchors.mjs';
import { noClientScripts } from './src/lib/no-client-scripts.mjs';

// The biography's last real content change (its `updated` frontmatter), used
// as its sitemap lastmod. The home page gets none: a build date would claim it
// changes on every deploy.
const aboutUpdated = readFileSync('./src/content/about.md', 'utf8').match(
  /^updated:\s*(\d{4}-\d{2}-\d{2})/m,
)?.[1];

// https://astro.build/config
export default defineConfig({
  site: 'https://austinfalk.com',
  // No trailing slashes: /about, not /about/. Pages build as files
  // (about.html) so Cloudflare serves them at the slash-less URL.
  trailingSlash: 'never',
  build: {
    format: 'file',
    // The one stylesheet is small; inlining it removes the only
    // render-blocking request.
    inlineStylesheets: 'always',
  },
  // Outfit, self-hosted at build time, Latin subset only, with a preload and
  // metric-matched fallback generated by Astro.
  fonts: [
    {
      provider: fontProviders.fontsource(),
      name: 'Outfit',
      cssVariable: '--font-outfit',
      weights: ['100 900'],
      styles: ['normal'],
      subsets: ['latin'],
      fallbacks: ['sans-serif'],
    },
  ],
  // Markdown headings get a "#" link to themselves (src/lib/heading-anchors.mjs).
  markdown: {
    processor: satteri({ hastPlugins: [headingAnchors] }),
  },
  integrations: [
    // React renders shadcn components to static HTML at build time only.
    react(),
    // Fails the build if any page can run JavaScript (src/lib/no-client-scripts.mjs).
    noClientScripts,
    sitemap({
      namespaces: { news: false, video: false, image: false, xhtml: false },
      serialize: (item) =>
        item.url.endsWith('/about') && aboutUpdated ? { ...item, lastmod: aboutUpdated } : item,
    }),
  ],
  vite: {
    plugins: [tailwindcss()],
  },
});
